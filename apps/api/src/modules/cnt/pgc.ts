/** Naturaleza de una cuenta según su código (para el plan de cuentas). */
export function naturalezaDe(codigo: string): string {
  const g = codigo[0];
  if (g === '6') return 'gasto';
  if (g === '7') return 'ingreso';
  if (g === '2' || g === '3') return 'activo';
  if (g === '1') return codigo.startsWith('17') || codigo.startsWith('16') || codigo.startsWith('14') || codigo.startsWith('18') ? 'pasivo' : 'patrimonio';
  if (/^(40|41|465|475|476|477|479|485|52|55|56)/.test(codigo)) return 'pasivo';
  if (/^(43|44|46|47|48|57|54)/.test(codigo)) return 'activo';
  return 'mixta';
}
